-- PostgreSQL implementation of the 18 documented business records.

CREATE TABLE user_account (
 user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE RESTRICT, role TEXT NOT NULL CHECK(role IN ('Administrator','Owner','Customer')),
 full_name TEXT NOT NULL, login_name TEXT NOT NULL UNIQUE,
 status TEXT NOT NULL DEFAULT 'Active' CHECK(status IN ('Active','Inactive')), created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE sme (
 sme_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id UUID NOT NULL REFERENCES user_account(user_id),
 store_name TEXT NOT NULL, business_type TEXT NOT NULL, address TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'Pending' CHECK(status IN ('Pending','Active','Inactive')), registered_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE category (
 category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, category_name TEXT NOT NULL  UNIQUE,
 product_type TEXT NOT NULL CHECK(product_type IN ('Packaged Product','Clothing','Gadget','General Retail')),
 status TEXT NOT NULL DEFAULT 'Active' CHECK(status IN ('Active','Archived'))
);
CREATE TABLE brand (
 brand_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, brand_name TEXT NOT NULL, search_key TEXT NOT NULL UNIQUE,
 status TEXT NOT NULL DEFAULT 'Active' CHECK(status IN ('Active','Archived'))
);
CREATE TABLE product (
 product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, category_id INTEGER NOT NULL REFERENCES category(category_id),
 brand_id INTEGER REFERENCES brand(brand_id), product_name TEXT NOT NULL, model_or_style TEXT,
 status TEXT NOT NULL DEFAULT 'Draft' CHECK(status IN ('Draft','Active','Archived'))
);
CREATE TABLE product_variation (
 variation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id INTEGER NOT NULL REFERENCES product(product_id),
 variation_name TEXT NOT NULL, size TEXT, color TEXT, flavor TEXT, capacity TEXT,
 net_quantity NUMERIC CHECK(net_quantity IS NULL OR net_quantity>0), net_unit TEXT CHECK(net_unit IN ('g','mL')),
 condition TEXT NOT NULL DEFAULT 'New' CHECK(condition IN ('New','Used')), stock_unit TEXT NOT NULL,
 other_details TEXT, variation_key TEXT NOT NULL, allow_price_reference BOOLEAN NOT NULL DEFAULT false,
 status TEXT NOT NULL DEFAULT 'Active' CHECK(status IN ('Active','Archived')),
 UNIQUE(product_id,variation_key), CHECK((net_quantity IS NULL)=(net_unit IS NULL))
);
CREATE TABLE product_unit (
 unit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, variation_id INTEGER NOT NULL REFERENCES product_variation(variation_id),
 unit_name TEXT NOT NULL , stock_units INTEGER NOT NULL CHECK(stock_units>0), gtin TEXT UNIQUE,
 status TEXT NOT NULL DEFAULT 'Active' CHECK(status IN ('Active','Archived')), UNIQUE(variation_id,unit_name,stock_units)
);
CREATE TABLE product_request (
 product_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sme_id INTEGER NOT NULL REFERENCES sme(sme_id), submitted_by UUID NOT NULL REFERENCES user_account(user_id),
 requested_details TEXT NOT NULL, submitted_at TIMESTAMPTZ NOT NULL,
 status TEXT NOT NULL DEFAULT 'Pending Product Review' CHECK(status IN ('Pending Product Review','Approved','Rejected')),
 reviewed_by UUID REFERENCES user_account(user_id), reviewed_at TIMESTAMPTZ, decision_reason TEXT,
 approved_variation_id INTEGER REFERENCES product_variation(variation_id), approved_unit_id INTEGER REFERENCES product_unit(unit_id)
);
CREATE TABLE store_product (
 store_product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sme_id INTEGER NOT NULL REFERENCES sme(sme_id), variation_id INTEGER NOT NULL REFERENCES product_variation(variation_id),
 stock_quantity INTEGER NOT NULL DEFAULT 0 CHECK(stock_quantity>=0), low_stock_level INTEGER NOT NULL DEFAULT 0 CHECK(low_stock_level>=0),
 latest_unit_cost NUMERIC CHECK(latest_unit_cost IS NULL OR latest_unit_cost>=0), status TEXT NOT NULL DEFAULT 'Active' CHECK(status IN ('Active','Archived')),
 UNIQUE(sme_id,variation_id)
);
CREATE TABLE store_price (
 store_price_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, store_product_id INTEGER NOT NULL REFERENCES store_product(store_product_id), unit_id INTEGER NOT NULL REFERENCES product_unit(unit_id),
 regular_price NUMERIC CHECK(regular_price IS NULL OR regular_price>0), price_updated_at TIMESTAMPTZ,
 status TEXT NOT NULL DEFAULT 'Active' CHECK(status IN ('Active','Archived')), UNIQUE(store_product_id,unit_id)
);
CREATE TABLE price_rule (
 rule_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, allowance_percent NUMERIC NOT NULL CHECK(allowance_percent>=0), minimum_stores INTEGER NOT NULL CHECK(minimum_stores>0),
 maximum_age_days INTEGER NOT NULL CHECK(maximum_age_days>0), effective_from TIMESTAMPTZ NOT NULL, created_by UUID NOT NULL REFERENCES user_account(user_id),
 status TEXT NOT NULL DEFAULT 'Active' CHECK(status IN ('Active','Inactive'))
);
CREATE UNIQUE INDEX one_active_rule ON price_rule(status) WHERE status='Active';
CREATE TABLE price_request (
 price_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, store_price_id INTEGER NOT NULL REFERENCES store_price(store_price_id), submitted_by UUID NOT NULL REFERENCES user_account(user_id),
 previous_price NUMERIC, proposed_price NUMERIC NOT NULL CHECK(proposed_price>0), owner_reason TEXT,
 submitted_at TIMESTAMPTZ NOT NULL, checked_at TIMESTAMPTZ, rule_id INTEGER REFERENCES price_rule(rule_id), reference_median NUMERIC,
 reference_count INTEGER NOT NULL DEFAULT 0 CHECK(reference_count>=0), allowed_price NUMERIC, review_reason TEXT,
 status TEXT NOT NULL DEFAULT 'Pending Price Review' CHECK(status IN ('Pending Price Review','Approved','Rejected','Withdrawn')),
 decision_source TEXT CHECK(decision_source IN ('System','Administrator')), reviewed_by UUID REFERENCES user_account(user_id), decided_at TIMESTAMPTZ, decision_reason TEXT,
 previous_request_id INTEGER REFERENCES price_request(price_request_id)
);
CREATE UNIQUE INDEX one_pending_price ON price_request(store_price_id) WHERE status='Pending Price Review';
CREATE TABLE price_request_evidence (
 price_request_id bigint PRIMARY KEY REFERENCES public.price_request(price_request_id),
 snapshot jsonb NOT NULL,
 policy_snapshot jsonb NOT NULL
);
CREATE TABLE price_reference (
 price_request_id INTEGER NOT NULL REFERENCES price_request(price_request_id), reference_sme_id INTEGER NOT NULL REFERENCES sme(sme_id),
 price_history_id INTEGER NOT NULL, PRIMARY KEY(price_request_id,reference_sme_id)
);
CREATE TABLE price_history (
 price_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, store_price_id INTEGER NOT NULL REFERENCES store_price(store_price_id),
 price_request_id INTEGER NOT NULL UNIQUE REFERENCES price_request(price_request_id), old_price NUMERIC, new_price NUMERIC NOT NULL CHECK(new_price>0), effective_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE stock_transaction (
 stock_transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, store_product_id INTEGER NOT NULL REFERENCES store_product(store_product_id), recorded_by UUID NOT NULL REFERENCES user_account(user_id),
 transaction_type TEXT NOT NULL CHECK(transaction_type IN ('Opening','Restock','Sale','Loss','Spoilage','Damage','Correction','Reversal')),
 quantity_change INTEGER NOT NULL, unit_id INTEGER REFERENCES product_unit(unit_id), entered_quantity INTEGER CHECK(entered_quantity IS NULL OR entered_quantity>0),
 units_per_package INTEGER CHECK(units_per_package IS NULL OR units_per_package>0), total_purchase_cost NUMERIC, total_sale_amount NUMERIC,
 unit_purchase_cost NUMERIC CHECK(unit_purchase_cost IS NULL OR unit_purchase_cost>=0), price_history_id INTEGER REFERENCES price_history(price_history_id),
 promotion_entry_id INTEGER, correction_of_id INTEGER REFERENCES stock_transaction(stock_transaction_id),
 reason TEXT, recorded_at TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX one_opening ON stock_transaction(store_product_id) WHERE transaction_type='Opening';
CREATE UNIQUE INDEX one_reversal ON stock_transaction(correction_of_id) WHERE transaction_type='Reversal';
CREATE TABLE promotion (
 promotion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, promotion_name TEXT NOT NULL, description TEXT, starts_at TIMESTAMPTZ NOT NULL, ends_at TIMESTAMPTZ NOT NULL CHECK(ends_at>starts_at),
 created_by UUID NOT NULL REFERENCES user_account(user_id), status TEXT NOT NULL DEFAULT 'Open' CHECK(status IN ('Open','Cancelled'))
);
CREATE TABLE promotion_entry (
 promotion_entry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, promotion_id INTEGER NOT NULL REFERENCES promotion(promotion_id), store_price_id INTEGER NOT NULL REFERENCES store_price(store_price_id),
 submitted_by UUID NOT NULL REFERENCES user_account(user_id), submitted_at TIMESTAMPTZ NOT NULL, promotion_price NUMERIC NOT NULL CHECK(promotion_price>0),
 regular_history_id INTEGER NOT NULL REFERENCES price_history(price_history_id), status TEXT NOT NULL DEFAULT 'Pending' CHECK(status IN ('Pending','Approved','Rejected','Withdrawn')),
 reviewed_by UUID REFERENCES user_account(user_id), decided_at TIMESTAMPTZ, decision_reason TEXT, previous_entry_id INTEGER REFERENCES promotion_entry(promotion_entry_id)
);
CREATE UNIQUE INDEX one_live_promo_submission ON promotion_entry(promotion_id,store_price_id) WHERE status IN ('Pending','Approved');
CREATE TABLE customer_report (
 customer_report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id UUID NOT NULL REFERENCES user_account(user_id), store_price_id INTEGER NOT NULL REFERENCES store_price(store_price_id),
 listed_price NUMERIC NOT NULL CHECK(listed_price>0), charged_price NUMERIC CHECK(charged_price IS NULL OR charged_price>0), transaction_at TIMESTAMPTZ, description TEXT NOT NULL,
 evidence_reference TEXT, submitted_at TIMESTAMPTZ NOT NULL, owner_response TEXT, responded_by UUID REFERENCES user_account(user_id), responded_at TIMESTAMPTZ,
 status TEXT NOT NULL DEFAULT 'Open' CHECK(status IN ('Open','Under Review','Closed')), reviewed_by UUID REFERENCES user_account(user_id),
 outcome TEXT CHECK(outcome IN ('Confirmed Discrepancy','Package Mismatch','Insufficient Evidence','No Discrepancy Established')), outcome_details TEXT, closed_at TIMESTAMPTZ,
 owner_response_requested_at TIMESTAMPTZ, owner_response_requested_by UUID REFERENCES user_account(user_id), no_response_reason TEXT,
 CONSTRAINT report_response_request_recorded CHECK ((owner_response_requested_by IS NULL) = (owner_response_requested_at IS NULL)),
 CONSTRAINT report_no_response_reason_correct_state CHECK (no_response_reason IS NULL OR (status='Closed' AND owner_response IS NULL))
);

CREATE INDEX store_owner ON sme(owner_id);
CREATE INDEX variation_product ON product_variation(product_id);
CREATE INDEX stock_store ON store_product(sme_id);
CREATE INDEX price_product ON store_price(store_product_id);
CREATE INDEX history_option ON price_history(store_price_id,price_history_id);
CREATE INDEX stock_product_date ON stock_transaction(store_product_id,recorded_at);
CREATE INDEX request_status ON price_request(status,submitted_at);
CREATE INDEX concern_status ON customer_report(status,customer_id);
CREATE INDEX customer_report_response_request_actor ON customer_report(owner_response_requested_by);
CREATE INDEX promo_option ON promotion_entry(store_price_id,status);

ALTER TABLE price_reference ADD FOREIGN KEY(price_history_id) REFERENCES price_history(price_history_id);
ALTER TABLE stock_transaction ADD FOREIGN KEY(promotion_entry_id) REFERENCES promotion_entry(promotion_entry_id);

CREATE UNIQUE INDEX category_name_key ON category(lower(trim(category_name)));
CREATE UNIQUE INDEX unit_gtin ON product_unit(gtin) WHERE gtin IS NOT NULL;
